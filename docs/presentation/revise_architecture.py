"""Editable architecture figures; panel bounds and connector endpoints support geometric QA."""
from pathlib import Path
from xml.sax.saxutils import escape
ROOT=Path(__file__).resolve().parents[2]; OUT=ROOT/'output/presentation/wind_aware_mbd/assets'
N,B,P,G,O,GR='#00274c','#2474bf','#9b4682','#008653','#d77717','#667889'
s=[]
def add(v):s.append(v)
def start(w,h,title):
 s.clear();add(f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}"><title>{escape(title)}</title><defs>')
 for c in [N,B,P,G,O,GR]:
  add(f'<marker id="a{c[1:]}" markerUnits="userSpaceOnUse" markerWidth="14" markerHeight="12" refX="13" refY="6" orient="auto"><path d="M0,0 L13,6 L0,12 Z" fill="{c}"/></marker>')
 add('</defs><rect width="100%" height="100%" fill="white"/>')
def save(name):add('</svg>');(OUT/name).write_text('\n'.join(s));print(name)
def rect(x,y,w,h,fill='white',stroke='#b5c7d6',rx=12):add(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{rx}" fill="{fill}" stroke="{stroke}" stroke-width="2"/>')
def panel(id,x,y,w,h,fill='#fbfcfe',stroke='#b5c7d6'):
 add(f'<g id="{id}" data-panel="{id}" data-bounds="{x},{y},{w},{h}">');rect(x,y,w,h,fill,stroke)
def end():add('</g>')
def text(x,y,t,sz=26,c=N,b=False,anchor='start'):add(f'<text x="{x}" y="{y}" font-family="Arial,Helvetica,sans-serif" font-size="{sz}" font-weight="{700 if b else 400}" fill="{c}" text-anchor="{anchor}">{escape(t)}</text>')
def rows(x,y,lines,sz=26,c=N,gap=43):
 for i,t in enumerate(lines):text(x,y+i*gap,t,sz,c)
def path(d,c=B,w=4,dash=''):add(f'<path d="{d}" fill="none" stroke="{c}" stroke-width="{w}"'+(f' stroke-dasharray="{dash}"' if dash else '')+'/>')
def arrow(points,c=N,w=3,source='',target=''):
 add(f'<polyline data-connector="{source}:{target}" points="{points}" fill="none" stroke="{c}" stroke-width="{w}" stroke-linejoin="round" marker-end="url(#a{c[1:]})"/>')
def dot(x,y,r,c,opacity=1):add(f'<circle cx="{x}" cy="{y}" r="{r}" fill="{c}" opacity="{opacity}"/>')
def badge(x,y,n,title,c=N,sz=27):
 dot(x,y,21,c);text(x,y+9,str(n),26,'white',True,'middle');text(x+35,y+9,title,sz,c,True)
def world(x,y,w,h,fan=False,obs=False):
 rect(x,y,w,h,'#f5f8fb','#d0dce5',6)
 rect(x+.04*w,y+.64*h,.22*w,.28*h,'#dce7f0','#b3c9da',1);text(x+.15*w,y+.84*h,'B',22,N,True,'middle')
 rect(x+.74*w,y+.08*h,.22*w,.28*h,'#dce7f0','#b3c9da',1);text(x+.85*w,y+.28*h,'A',22,N,True,'middle')
 dot(x+.48*w,y+.40*h,.13*h,'#9aa9b6');dot(x+.6*w,y+.69*h,.13*h,'#9aa9b6')
 for a,b in [(.23,.16),(.48,.15),(.82,.65),(.25,.48)]:arrow(f'{x+a*w},{y+b*h} {x+(a-.07)*w},{y+(b+.06)*h}',GR,1.8)
 path(f'M{x+.83*w},{y+.25*h} L{x+.15*w},{y+.78*h}',O,3,'8 6')
 if fan:
  for a in [.35,.55,.75]:path(f'M{x+.83*w},{y+.25*h} Q{x+a*w},{y+.99*h} {x+.15*w},{y+.78*h}',O,2.5,'7 5')
 else:
  path(f'M{x+.83*w},{y+.25*h} C{x+.97*w},{y+.83*h} {x+.48*w},{y+.98*h} {x+.15*w},{y+.78*h}',B,4)
  dot(x+.68*w,y+.78*h,10,B,.15);dot(x+.68*w,y+.78*h,5,B)
  if obs:
   for a,b in [(.85,.38),(.85,.5),(.81,.62),(.72,.73)]:dot(x+a*w,y+b*h,4,P)
def cost(x,y,w,h):
 path(f'M{x},{y} V{y+h} H{x+w}',GR,2)
 add(f'<path d="M{x+5},{y+.28*h} C{x+.25*w},{y+.7*h} {x+.48*w},{y+.21*h} {x+.6*w},{y+.47*h} S{x+.84*w},{y+.7*h} {x+w-10},{y+.35*h} L{x+w-10},{y+h-2} H{x+5} Z" fill="{B}" opacity=".16"/>')
 path(f'M{x+5},{y+.28*h} C{x+.25*w},{y+.7*h} {x+.48*w},{y+.21*h} {x+.6*w},{y+.47*h} S{x+.84*w},{y+.7*h} {x+w-10},{y+.35*h}',B,4)
